"""Static invariants of the collision_monitor ToF sources and the CliffStop polygon (design D4, D5; U1, U5).

The head ToF cloud (/tof/points_filtered) feeds two collision_monitor pointcloud sources: `tof_obstacles` (3D
obstacles, into StopBox next to the lidar) and `tof_cliff` (below-floor points, into the CliffStop approach polygon
generated by scripts/gen_nav_footprint.py). The lidar `scan` source stays unchanged (U5). Both ToF sources keep the
node source_timeout, so a ToF or head-TF outage stops motion ("invalid source"). No ROS is available on the dev
machine, so the YAML is read directly; the CliffStop behaviour is checked against a port of the nav2 1.3.13 approach
model (VelocityPolygon::isInRange, Polygon::getCollisionTime).
"""


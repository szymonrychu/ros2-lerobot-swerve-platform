"""Static invariants of the collision_monitor ToF sources and the CliffStop polygon (design D4, D5; U1, U5).

The head ToF cloud (/tof/points_filtered) feeds two collision_monitor pointcloud sources: `tof_obstacles` (3D
obstacles, into StopBox next to the lidar) and `tof_cliff` (below-floor points, into the CliffStop approach polygon
generated by scripts/gen_nav_footprint.py). The lidar `scan` source stays unchanged (U5). Both ToF sources keep the
node source_timeout, so a ToF or head-TF outage stops motion ("invalid source"). No ROS is available on the dev
machine, so the YAML is read directly.
"""

import ast
from pathlib import Path

import pytest
import yaml

from scripts.gen_nav_footprint import DEFAULT_CONFIG, generate, load_settings

REPO_ROOT = Path(__file__).resolve().parent.parent
NAV2_PARAMS = REPO_ROOT / "nodes" / "nav2_bringup" / "config" / "nav2_params.yaml"
NAV2_README = REPO_ROOT / "nodes" / "nav2_bringup" / "README.md"
TESTS_README = REPO_ROOT / "tests" / "README.md"

TOF_TOPIC = "/tof/points_filtered"
FILTERED_SCAN = "/scan_filtered"
TOF_SOURCES = ("tof_obstacles", "tof_cliff")
# collision_monitor source -> the STVL mark source of the local costmap that uses the same height band.
STVL_BAND = {"tof_obstacles": "tof_mark", "tof_cliff": "tof_cliff_mark"}
OBSERVATION_SOURCES = ["scan", "tof_obstacles", "tof_cliff"]
POLYGONS = ["StopBox", "ArmStop", "CliffStop"]
POLYGON_SOURCES = {
    "StopBox": ["scan", "tof_obstacles"],
    "ArmStop": ["scan"],
    "CliffStop": ["tof_cliff"],
}
EXPECTED_TOF_SOURCES = {
    "tof_obstacles": {
        "type": "pointcloud",
        "topic": TOF_TOPIC,
        "min_height": 0.06,
        "max_height": 0.6,
        "min_range": 0.0,
        "enabled": True,
    },
    "tof_cliff": {
        "type": "pointcloud",
        "topic": TOF_TOPIC,
        "min_height": -1.0,
        "max_height": -0.10,
        "min_range": 0.0,
        "enabled": True,
    },
}
PARKING_PHRASES = ("to tune", "starting value", "later", "follow-up", "todo", "phase 2", "out of scope")
DOCKER_SECTION = "## ToF validation in Docker"


def collision_monitor() -> dict:
    """ros__parameters of the collision_monitor in the repo Nav2 params.

    Returns:
        dict: The collision_monitor parameters.
    """
    return yaml.safe_load(NAV2_PARAMS.read_text())["collision_monitor"]["ros__parameters"]


def stvl_layer() -> dict:
    """The tof_voxel_layer block of the local costmap.

    Returns:
        dict: STVL layer parameters.
    """
    doc = yaml.safe_load(NAV2_PARAMS.read_text())
    return doc["local_costmap"]["local_costmap"]["ros__parameters"]["tof_voxel_layer"]


def collision_monitor_text() -> str:
    """Raw text of the collision_monitor block (to check comments).

    Returns:
        str: Lines from `collision_monitor:` up to the next top-level key.
    """
    lines = NAV2_PARAMS.read_text().splitlines()
    start = lines.index("collision_monitor:")
    end = start + 1
    while end < len(lines) and (not lines[end] or lines[end].startswith((" ", "#"))):
        end += 1
    return "\n".join(lines[start:end])


def readme_section(text: str, heading: str) -> str:
    """Body of one `## ` section of a markdown text (up to the next `## ` heading).

    Args:
        text: Markdown text.
        heading: Full heading line, e.g. `## Collision monitor`.

    Returns:
        str: The section body (subsections included).
    """
    assert heading in text, heading
    return text.split(heading, 1)[1].split("\n## ", 1)[0]


def test_observation_sources_are_scan_and_the_two_tof_sources() -> None:
    assert collision_monitor()["observation_sources"] == OBSERVATION_SOURCES


@pytest.mark.parametrize("source", TOF_SOURCES)
def test_tof_source_settings(source: str) -> None:
    actual = collision_monitor()[source]
    for key, value in EXPECTED_TOF_SOURCES[source].items():
        assert type(actual[key]) is type(value), f"{source}.{key}"
        assert actual[key] == value, f"{source}.{key}"


@pytest.mark.parametrize("source", TOF_SOURCES)
def test_tof_source_band_equals_the_stvl_mark_band(source: str) -> None:
    """The monitor and the local costmap agree on what an obstacle / a cliff is (pointcloud heights compare in the
    base frame, STVL heights in odom; both have the floor at z = 0)."""
    actual = collision_monitor()[source]
    mark = stvl_layer()[STVL_BAND[source]]
    assert (actual["min_height"], actual["max_height"]) == (mark["min_obstacle_height"], mark["max_obstacle_height"])
    assert actual["topic"] == mark["topic"] == TOF_TOPIC


def test_scan_source_is_unchanged() -> None:
    """U5: the lidar keeps guarding all around next to the ToF sources."""
    scan = collision_monitor()["scan"]
    assert scan == {"type": "scan", "topic": FILTERED_SCAN, "enabled": True}


def test_polygons_include_cliffstop() -> None:
    assert collision_monitor()["polygons"] == POLYGONS


def test_every_polygon_names_only_declared_sources() -> None:
    cm = collision_monitor()
    declared = set(cm["observation_sources"])
    for name in cm["polygons"]:
        names = cm[name]["sources_names"]
        assert names, f"{name} has no sources_names (it would default to every source)"
        assert set(names) <= declared, f"{name}: {set(names) - declared} not in observation_sources"


@pytest.mark.parametrize(("polygon", "sources"), sorted(POLYGON_SOURCES.items()))
def test_polygon_source_sets(polygon: str, sources: list[str]) -> None:
    assert collision_monitor()[polygon]["sources_names"] == sources


def test_cliffstop_is_an_approach_polygon_with_the_generated_points() -> None:
    cliff = collision_monitor()["CliffStop"]
    assert cliff["type"] == "polygon"
    assert cliff["action_type"] == "approach"
    assert cliff["time_before_collision"] > 0
    assert cliff["enabled"] is True
    generated = generate(load_settings(DEFAULT_CONFIG), REPO_ROOT)
    assert yaml.safe_load(cliff["points"]) == [list(p) for p in generated.cliff_polygon]


def test_tof_sources_keep_the_stale_source_stop() -> None:
    """A ToF or head-TF outage stops Nav2 motion (user decision 2026-10-18): no ToF source sets source_timeout 0.0
    (which disables the invalid-source stop); both inherit the node's non-zero source_timeout."""
    cm = collision_monitor()
    assert cm["source_timeout"] == 1.0
    for source in TOF_SOURCES:
        assert "source_timeout" not in cm[source], f"{source} overrides the node source_timeout"
        assert cm[source]["enabled"] is True


def test_comments_explain_the_outage_stop_and_the_runtime_switch() -> None:
    text = collision_monitor_text()
    for phrase in (
        "invalid source",
        "collision_monitor_node.cpp",
        "ros2 param set /collision_monitor tof_cliff.enabled false",
        "edge noise",
        "arm shadow",
    ):
        assert phrase in text, phrase


def test_cliffstop_comment_states_that_points_inside_stop_every_motion() -> None:
    """Docker check 2026-10-18: with 4+ cliff points already inside CliffStop the approach model stops backing away
    too (nav2 1.3.13 Polygon::getCollisionTime returns 0 for points inside the polygon); the comment must say so."""
    text = collision_monitor_text()
    cliff = text.split("\n    CliffStop:\n", 1)[0].rsplit("\n    ArmStop:\n", 1)[1]
    assert "getCollisionTime" in cliff
    assert "every motion" in cliff



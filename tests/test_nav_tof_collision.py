def collision_monitor() -> dict:
    """ros__parameters of the collision_monitor in the repo Nav2 params.

    Returns:
        dict: The collision_monitor parameters.
    """
    return yaml.safe_load(NAV2_PARAMS.read_text())["collision_monitor"]["ros__parameters"]


def stvl_layer() -> dict:
    """The tof_voxel_layer block of the local costmap.

    Returns:
        dict: STVL layer parameters.
    """
    doc = yaml.safe_load(NAV2_PARAMS.read_text())
    return doc["local_costmap"]["local_costmap"]["ros__parameters"]["tof_voxel_layer"]


def collision_monitor_text() -> str:
    """Raw text of the collision_monitor block (to check comments).

    Returns:
        str: Lines from `collision_monitor:` up to the next top-level key.
    """
    lines = NAV2_PARAMS.read_text().splitlines()
    start = lines.index("collision_monitor:")
    end = start + 1
    while end < len(lines) and (not lines[end] or lines[end].startswith((" ", "#"))):
        end += 1
    return "\n".join(lines[start:end])


def readme_section(text: str, heading: str) -> str:
    """Body of one `## ` section of a markdown text (up to the next `## ` heading).

    Args:
        text: Markdown text.
        heading: Full heading line, e.g. `## Collision monitor`.

    Returns:
        str: The section body (subsections included).
    """
    assert heading in text, heading
    return text.split(heading, 1)[1].split("\n## ", 1)[0]



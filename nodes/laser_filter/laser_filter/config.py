"""laser_filter configuration (pydantic): topics, polygon frame and the startup self polygon."""

import os
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field, field_validator

from .self_filter import parse_polygon

ENV_CONFIG_PATH_KEY = "LASER_FILTER_CONFIG"
DEFAULT_CONFIG_PATH = Path("/etc/ros2/laser_filter/config.yaml")


class LaserFilterConfig(BaseModel):
    """Validated footprint_filter.yaml."""

    model_config = ConfigDict(extra="forbid")

    scan_topic: str = "/scan"
    scan_filtered_topic: str = "/scan_filtered"
    polygon_frame: str = "base_link"
    # Longest wait for the polygon_frame -> scan frame TF per scan before the scan is dropped (s).
    transform_timeout_s: float = Field(default=0.1, ge=0.0, le=10.0)
    # Startup self polygon "[[x, y], ...]" in polygon_frame (generated by scripts/gen_nav_footprint.py).
    polygon: str

    @field_validator("polygon")
    @classmethod
    def valid_polygon(cls, value: str) -> str:
        """Require a parsable polygon of at least three points.

        Args:
            value (str): Polygon string.

        Returns:
            str: The value.
        """
        parse_polygon(value)
        return value


def load_config(path: Path) -> LaserFilterConfig:
    """Load and validate the config file.

    Args:
        path (Path): YAML file.

    Returns:
        LaserFilterConfig: Validated config.
    """
    return LaserFilterConfig.model_validate(yaml.safe_load(path.read_text()) or {})


def config_path_from_env() -> Path:
    """Config path: $LASER_FILTER_CONFIG, else DEFAULT_CONFIG_PATH.

    Returns:
        Path: Config file path.
    """
    return Path(os.environ.get(ENV_CONFIG_PATH_KEY, str(DEFAULT_CONFIG_PATH)))
